namespace backend\controllers;

use common\models\Product;
use Yii;
use cnd\admin\models\activerecords\Log;
use cnd\core\components\SController;
use cnd\grid\DataLocator;
use common\models\ProductDetail;

class ProductDetailsController extends SController
{

    public $product;
    public $target;

    public function beforeAction($action)
    {
        if (Yii::$app->request->get('t')) {
            $this->target = Yii::$app->request->get('t');
        }
        if (Yii::$app->request->get('p')) {
            $this->product = Product::find()->where(['id' => Yii::$app->request->get('p')])->one();
            if (!$this->product) {
                \Yii::$app->session->setFlash('error', 'Product not found');
                $this->goBack();
                return null;
            }
        }
        // redirect to detials items
        $detail = ProductDetail::find()->where(['product_id' => $this->product->id])->one();
        if(!$detail){
            $detail = new ProductDetail();
            $detail->title = "Product Details";
            $detail->section = ProductDetail::SECTION_COMPANY;
            $detail->product_id = $this->product->id;
            $detail->save();
        }
        $this->redirect(['/product-details-item/index','p' => $this->product->id, 't' => $this->target, 'd' => $detail->id]);
        return null;
        //return parent::beforeAction($action); // TODO: Change the autogenerated stub
    }

    public function actionIndex()
    {
        /**
         * @var $dataLocator DataLocator
         */
        $dataLocator = DataLocator::create(ProductDetail::className(), [
            'orderBy' => 'updated_at DESC, created_at DESC, id DESC',
            'params' => [
                't' => $this->target,
                'p' => $this->product->id,
            ],
            'pageSize' => 20,
        ], function ($dl, $query) {
            $query->andWhere(['product_id' => $this->product->id]);
        });
        Log::trace("Show Product Details List (page:" . $dataLocator->page . ", count: " . $dataLocator->pageSize . ")");
        if (Yii::$app->request->isAjax) {
            return $this->renderAjax('index', ['dataLocator' => $dataLocator]);
        }
        return $this->render('index', ['dataLocator' => $dataLocator]);
    }

    public function actionManage($id = null)
    {
        $model = ProductDetail::findOne($id);
        if (!$model) {
            $model = new ProductDetail();
            $model->product_id = $this->product->id;
        }
        if ($model === null) {
            throw new \yii\web\HttpException(404, 'The requested Product Details could not be found.');
        }
        $isNew = $model->isNewRecord;
        if ($model->load(\Yii::$app->request->post()) && $model->validate()) {
            if ($model->save()) {
                \Yii::$app->session->setFlash('success', ucfirst($this->id) . ' saved successfully');
            } else {
                \Yii::$app->session->setFlash('error', ucfirst($this->id) . ' not saved');
            }
            if ($isNew) {
                Log::trace("Create new Product Details #" . $model->id);
            } else {
                Log::trace("Update Product Details #" . $id);
            }
            return $this->redirect(['index', 'p' => $this->product->id, 't' => $this->target]);
        }
        Log::trace("Open Product Details form");
        return $this->render('form', ['model' => $model]);
    }

    public function actionDelete($id)
    {
        $model = ProductDetail::find()->where(['id' => $id])->one();
        if ($model !== null) {
            if ($model->delete()) {
                Log::trace("Product Details deleted #" . $id);
                \Yii::$app->session->setFlash('success', ucfirst($this->id) . ' deleted successfully');
            } else {
                Log::trace("Product Details not deleted #" . $id);
                \Yii::$app->session->setFlash('error', ucfirst($this->id) . ' not deleted');
            }
        } else {
            Log::trace("Product Details not found to delete #" . $id);
            \Yii::$app->session->setFlash('error', ucfirst($this->id) . ' not found');
        }
        return $this->redirect(['index', 'p' => $this->product->id, 't' => $this->target]);
    }
}
