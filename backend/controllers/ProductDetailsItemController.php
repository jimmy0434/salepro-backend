namespace backend\controllers;

use cnd\admin\models\activerecords\Log;
use cnd\grid\DataLocator;
use common\models\Product;
use common\models\ProductDetail;
use common\models\ProductDetailItem;
use Yii;
use cnd\core\components\SController;

class ProductDetailsItemController extends SController
{
    public $product;
    public $target;
    public $detail;

    public function beforeAction($action)
    {
        if (Yii::$app->request->get('t')) {
            $this->target = Yii::$app->request->get('t');
        }
        if (Yii::$app->request->get('p')) {
            $this->product = Product::find()->where(['id' => Yii::$app->request->get('p')])->one();
            if (!$this->product) {
                \Yii::$app->session->setFlash('error', 'Product not found');
                $this->goBack();
                return null;
            }
        }
        if (Yii::$app->request->get('d')) {
            $this->detail = ProductDetail::find()->where(['id' => Yii::$app->request->get('d')])->one();
            if (!$this->detail) {
                \Yii::$app->session->setFlash('error', 'Product Details not found');
                $this->goBack();
                return null;
            }
        }
        return parent::beforeAction($action); // TODO: Change the autogenerated stub
    }

    public function actionIndex()
    {
        /**
         * @var $dataLocator DataLocator
         */
        $dataLocator = DataLocator::create(ProductDetailItem::className(), [
            'orderBy' => 'updated_at DESC, created_at DESC, id DESC',
            'params' => [
                't' => $this->target,
                'p' => $this->product->id,
                'd' => $this->detail->id,
            ],
            'pageSize' => 20,
        ], function ($dl, $query) {
            $query->andWhere(['product_detail_id' => $this->detail->id]);
        });
        Log::trace("Show Product Details Items List (page:" . $dataLocator->page . ", count: " . $dataLocator->pageSize . ")");
        if (Yii::$app->request->isAjax) {
            return $this->renderAjax('index', ['dataLocator' => $dataLocator]);
        }
        return $this->render('index', ['dataLocator' => $dataLocator]);
    }

    public function actionManage($id = null, $type = null)
    {
        $model = ProductDetailItem::findOne($id);
        if (!$model) {
            $model = new ProductDetailItem();
            $model->product_detail_id = $this->detail->id;
            $model->type = $type;
        }
        if ($model === null) {
            throw new \yii\web\HttpException(404, 'The requested Product Details Item could not be found.');
        }
        $isNew = $model->isNewRecord;
        if ($model->load(\Yii::$app->request->post()) && $model->validate()) {
            if ($model->save()) {
                \Yii::$app->session->setFlash('success', ucfirst($this->id) . ' saved successfully');
            } else {
                \Yii::$app->session->setFlash('error', ucfirst($this->id) . ' not saved');
            }
            if ($isNew) {
                Log::trace("Create new Product Details Item #" . $model->id);
            } else {
                Log::trace("Update Product Details Item #" . $id);
            }
            //if ($isNew || $model->type != ProductDetailItem::TYPE_FILE) {
                $model->productDetail->product->portfolio->sendNotification();
            //}
            return $this->redirect(['index', 'p' => $this->product->id, 't' => $this->target, 'd' => $this->detail->id]);
        }
        Log::trace("Open Product Details Item form");
        return $this->render('form', ['model' => $model]);
    }

    public function actionDelete($id)
    {
        $model = ProductDetailItem::find()->where(['id' => $id])->one();
        if ($model !== null) {
            if ($model->delete()) {
                Log::trace("Product Details Item deleted #" . $id);
                \Yii::$app->session->setFlash('success', ucfirst($this->id) . ' deleted successfully');
            } else {
                Log::trace("Product Details Item not deleted #" . $id);
                \Yii::$app->session->setFlash('error', ucfirst($this->id) . ' not deleted');
            }
        } else {
            Log::trace("Product Details Item not found to delete #" . $id);
            \Yii::$app->session->setFlash('error', ucfirst($this->id) . ' not found');
        }
        return $this->redirect(['index', 'p' => $this->product->id, 't' => $this->target, 'd' => $this->detail->id]);
    }
}
