    }

    public function sendNotification()
    {

        $users = array_values(ArrayHelper::map(User::find()->where(['type' => User::TYPE_SALESMAN, 'status' => User::STATUS_ACTIVE])->all(), 'id', 'id'));
        if (!empty($users) && is_array($users)) {
            Yii::$app->notification->send('country-profile-update', [
                'message' => 'Country Profile Update',
                'id' => $this->id,
                'uid' => $this->uid,
            ], $users);
        }


    }
    public function grantNotification($user, $granted)
    {
        Yii::$app->notification->send("country-profile-update-grant", [
            'message' => 'The country-profile `' . $this->name . '` was ' . ($granted ? 'enabled for' : 'disabled from') . ' watching.',
            'id' => $this->id,
            'uid' => $this->uid,
            'granted' => $granted,
        ], [$user->id]);
        $userName = $user->name;
        Log::trace('Grant country-profile permission', ($granted ? 'Enabled ' . $userName . ' to' : 'Disabled ' . $userName . ' from') . ' view the  country-profile `' . $this->name . '` #' . $this->id);
    }
}
