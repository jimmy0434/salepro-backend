<?php

namespace common\models;

use Yii;
use yii\helpers\ArrayHelper;
use yii\helpers\Json;

/**
 * This is the model class for table "{{%sustainability}}".
 *
 * @property int $id
 * @property string $name
 * @property string $image
 * @property int $file_id
 * @property int $position
 * @property string $type
 * @property int $created_at
 * @property int $updated_at
 *
 * @property array $type_list
 * @property array $type_values
 * @property string $type_label
 *
 * @property File $file
 */
class Sustainability extends \common\components\ActiveRecord
{

    const TYPE_DOWNLOAD_FILE = 'download';
    const TYPE_ENVIRONMENTAL_SUSTAINABILITY = 'environmental';
    const TYPE_SOCIAL_RESPONSIBILITY = 'social_responsibility';

    public $imageFactory;

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return '{{%sustainability}}';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return array_merge(parent::rules(), [
            [['name','position','file_id'], 'required'],
            [['file_id'], 'integer'],
            [['name'], 'string'],
            [['position'],'number','min'=>0, 'integerOnly' => true],
            [['file_id'], 'exist', 'skipOnError' => true, 'targetClass' => File::className(), 'targetAttribute' => ['file_id' => 'id']],
        ]);
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'name' => 'Name',
            'image' => 'Image',
            'file_id' => 'File',
            'position' => 'Position',
            'type' => 'Type',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    /**
     * @return \yii\db\ActiveQuery
     */
    public function getFile()
    {
        return $this->hasOne(File::className(), ['id' => 'file_id']);
    }

    /**
     * {@inheritdoc}
     * @return SustainabilityQuery the active query used by this AR class.
     */
    public static function find()
    {
        return new SustainabilityQuery(get_called_class());
    }

    public function beforeSave($insert)
    {
        if (is_array($this->image)) {
            $this->image = Json::encode($this->image);
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function afterFind()
    {
        parent::afterFind();
        if (is_string($this->image) && Yii::$app->helper->isJson($this->image)) {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => $this->image,
            ]);
        } else {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => Yii::$app->image->defaultUser,
            ]);
        }
    }

    public function toArray(array $fields = [], array $expand = [], $recursive = true)
    {
        $list = parent::toArray($fields, $expand, $recursive);
        unset($list['file_id']);
        $list['file'] = $this->file;
        $list['image'] = $this->imageFactory->url;
        return $list;
    }

    public function sendNotification()
    {
        $users = array_values(ArrayHelper::map(User::find()->where(['status' => User::STATUS_ACTIVE, 'type' => User::TYPE_SALESMAN])->all(), 'id', 'id'));
        Yii::$app->notification->send('sustainability-update', [
            'message' => 'Sustainability Update',
            'id' => $this->id,
        ], $users);
    }
}
