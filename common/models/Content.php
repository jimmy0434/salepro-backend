<?php

namespace common\models;

use Yii;
use yii\helpers\Json;

/**
 * This is the model class for table "{{%content}}".
 *
 * @property int $id
 * @property string $title
 * @property string $text
 * @property string $image
 * @property int $created_at
 * @property int $updated_at
 *
 * @property ProductDetailItem[] $productDetailItems
 */
class Content extends \cnd\core\components\ActiveRecord
{

    public $imageFactory;

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return '{{%content}}';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return array_merge(parent::rules(), [
            [['text'], 'string'],
            [['title'], 'string', 'max' => 255],
        ]);
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'title' => 'Title',
            'text' => 'Text',
            'image' => 'Image',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    /**
     * @return \yii\db\ActiveQuery
     */
    public function getProductDetailItems()
    {
        return $this->hasMany(ProductDetailItem::className(), ['content_id' => 'id']);
    }

    /**
     * {@inheritdoc}
     * @return ContentQuery the active query used by this AR class.
     */
    public static function find()
    {
        return new ContentQuery(get_called_class());
    }

    public static function add($title, $text, $image)
    {
        $model = new static();
        $model->title = $title;
        $model->text = $text;
        $model->image = $image;
        if ($model->save()) {
            return $model->id;
        }
        return null;
    }

    public function beforeSave($insert)
    {
        if (is_array($this->image)) {
            $this->image = Json::encode($this->image);
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function afterFind()
    {
        parent::afterFind();
        if (is_string($this->image) && Yii::$app->helper->isJson($this->image)) {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => $this->image,
            ]);
        } else {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => Yii::$app->image->defaultUser,
            ]);
        }
    }

    public function toArray(array $fields = [], array $expand = [], $recursive = true)
    {
        $data = parent::toArray($fields, $expand, $recursive);
        $data['image'] = $this->imageFactory->url;
        return $data;
    }
}
