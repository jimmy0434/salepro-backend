            $this->uid = uniqid('business-unit-', true);
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function afterFind()
    {
        parent::afterFind();
    }

    public static function listData()
    {
        return ArrayHelper::map(static::find()->from(['bu' => static::tableName()])->joinWith([
            'portfolio' => function ($query) {
                $query->from(['portfolio' => Portfolio::tableName()]);
            }
        ])->orderBy(['portfolio.name' => SORT_ASC])->all(), 'id', function ($model) {
            if ($model->portfolio) {
                return $model->portfolio->name;
            }
            return null;
        });
    }

    public static function relateToPortfolio($portfolioId)
    {
        $model = static::find()->where(['portfolio_id' => $portfolioId])->one();
        if (!$model) {
            $model = new static();
            $model->uid = uniqid('business-unit-', true);
            $model->portfolio_id = $portfolioId;
            $model->save();
        }
    }

