<?php

namespace common\models;

use yii\helpers\ArrayHelper;
use yii\helpers\Json;
use Yii;

/**
 * This is the model class for table "mpk_learning".
 *
 * @property int $id
 * @property string $uid
 * @property string $name
 * @property string $description
 * @property string $image
 * @property string $trainer
 * @property int $target
 * @property int $parent_id
 * @property int $search_id
 * @property int $file_id
 * @property int $created_at
 * @property int $updated_at
 */
class Learning extends \common\components\ActiveRecord
{

    public $tags = [];
    const TARGET_View1 = 1;
    const TARGET_View2 = 2;
    const TARGET_Items = 3;
    
    public $imageFactory;
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'mpk_learning';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
           
            [['target', 'parent_id', 'search_id', 'file_id', 'created_at', 'updated_at'], 'integer'],
            [['uid', 'name', 'description', 'trainer'], 'string', 'max' => 255],
            [['uid'], 'unique'],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'uid' => 'Uid',
            'name' => 'Name',
            'description' => 'Description',
            'image' => 'Image',
            'trainer' => 'Trainer',
            'target' => 'Target',
            'parent_id' => 'Parent ID',
            'search_id' => 'Search ID',
            'file_id' => 'File ID',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    /**
     * {@inheritdoc}
     * @return LearningQuery the active query used by this AR class.
     */
    public static function find()
    {
        return new LearningQuery(get_called_class());
    }
    public function afterFind()
    {
        parent::afterFind();
        if (is_string($this->image) && Yii::$app->helper->isJson($this->image)) {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => $this->image,
            ]);
        } else {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => Yii::$app->image->defaultUser,
            ]);
        }
    }
    public static function dropDownList($type)
    {
        return ArrayHelper::map(static::find()->orderBy(['name' => SORT_ASC])->where(['target' => $type])->all(), 'id', 'name');
    }

   
    public function beforeSave($insert)
    {
        if ($this->isNewRecord || !$this->uid) {
            $this->uid = uniqid('learning-', true);
        }
        if (is_array($this->image)) {
            $this->image = Json::encode($this->image);
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }


    public function toArray(array $fields = [], array $expand = [], $recursive = true)
    {
        $formatter = \Yii::$app->formatter;
        $list = parent::toArray($fields, $expand, $recursive);
       
        $list['image'] = $this->imageFactory->url;   
      //  $list['date'] = Yii::$app->formatter->asDate($this->created_at, 'php:Y-m-d');
    //  $list['created_at'] = strtotime($list['date']); 
      
        return $list;

        
        
    }
    
   
}

