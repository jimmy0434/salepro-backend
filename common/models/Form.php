use yii\db\Schema;
use yii\helpers\ArrayHelper;
use yii\helpers\Json;

/**
 * This is the model class for table "{{%form}}".
 *
 * @property int $id
 * @property int $content_id
 * @property string $name
 * @property string $title
 * @property int $version
 * @property int $status
 * @property string $structure
 * @property int $created_at
 * @property int $updated_at
 *
 * @property string $status_label
 * @property array $status_list
 * @property array $status_values
 *
 * @property Content $content
 */
class Form extends ActiveRecord
{
    const STATUS_ACTIVE = 10;
    const STATUS_PENDING = 5;
    const STATUS_INACTIVE = 1;

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return '{{%form}}';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return array_merge(parent::rules(), [
            [['name'], 'string', 'max' => 20],
            [['title'], 'string', 'max' => 255],
            [['name'], 'unique'],
            [['content_id'], 'exist', 'skipOnError' => true, 'targetClass' => Content::className(), 'targetAttribute' => ['content_id' => 'id']],
        ]);
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'content_id' => 'Content ID',
            'name' => 'Name',
            'title' => 'Title',
            'version' => 'Version',
            'status' => 'Status',
            'structure' => 'Structure',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    /**
     * @return \yii\db\ActiveQuery
     */
    public function getContent()
    {
        return $this->hasOne(Content::className(), ['id' => 'content_id']);
    }

    /**
     * {@inheritdoc}
     * @return FormQuery the active query used by this AR class.
     */
    public static function find()
    {
        return new FormQuery(get_called_class());
    }

    public function beforeSave($insert)
    {
        if (is_array($this->structure)) {
            $this->structure = Json::encode($this->structure);
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function afterFind()
    {
        parent::afterFind();
        if (!Yii::$app->helper->isJson($this->structure)) {
            $this->structure = [
                'id' => time(),
                'name' => $this->name,
                'oldName' => $this->name,
                'fields' => [],
                'isRoot' => true,
            ];
        } else {
            $this->structure = Json::decode($this->structure);
        }
    }

    public function synchronizeTables()
    {
        $transaction = Yii::$app->bi->beginTransaction();
        try {
            $structure = $this->structure;
            $this->manageTable($structure);
            $this->structure = $structure;
            $this->save(false);
            $transaction->commit();
        } catch (\Exception $e) {
            $transaction->rollBack();
        } catch (\Throwable $t) {
            $transaction->rollBack();
        }
        return $this->structure;
    }

    protected function manageTable(&$structure, $parentName = null)
    {

        $bi = Yii::$app->bi;
        $tableName = $this->createSlug(strtolower(($parentName && is_string($parentName) ? $parentName . "_" : "") . $structure['name']));
        $oldTableName = $this->createSlug(strtolower($structure['oldName']));
        $tables = $bi->schema->tableNames;
        // create table if not exist
        if ($tableName && !in_array($tableName, $tables) && !in_array($oldTableName, $tables)) {
            $options = 'CHARACTER SET utf8 COLLATE utf8_unicode_ci ENGINE=InnoDB';
            $columns = [];
            $columns['id'] = $bi->getSchema()->createColumnSchemaBuilder(Schema::TYPE_PK);
            $relation = null;
            if ($parentName && is_string($parentName)) {
                $relationColumnName = 'parent_relation_id';
                $columns[$relationColumnName] = $bi->getSchema()->createColumnSchemaBuilder(Schema::TYPE_INTEGER);
                $relation = function () use ($bi, $tableName, $relationColumnName, $parentName) {
                    $bi->createCommand()->createIndex(md5('idx' . $tableName . '-' . $relationColumnName), $tableName, $relationColumnName)->execute();
                    $bi->createCommand()->addForeignKey(md5('fk' . $tableName . '-' . $relationColumnName), $tableName, $relationColumnName, $parentName, 'id', 'CASCADE', 'CASCADE')->execute();
                };
            }
            $columns['created_at'] = $bi->getSchema()->createColumnSchemaBuilder(Schema::TYPE_INTEGER);
            $columns['updated_at'] = $bi->getSchema()->createColumnSchemaBuilder(Schema::TYPE_INTEGER);
            $bi->createCommand()->createTable($tableName, $columns, $options)->execute();
            if ($relation && is_callable($relation)) {
                $relation();
            }
            $structure['oldName'] = $structure['name'];
        } else if ($tableName && $tableName != $oldTableName && !in_array($tableName, $tables)) {
            // rename the table name
            $bi->createCommand()->renameTable($oldTableName, $tableName)->execute();
            $structure['oldName'] = $structure['name'];
        }
        // create columns if not exists
        $dataTypes = [];
        $columns = ArrayHelper::map($bi->schema->tableSchemas, 'name', function ($row) use (&$dataTypes) {
            if (!isset($dataTypes[$row->name])) {
                $dataTypes[$row->name] = [];
            }
            if (!empty($row->columns) && is_array($row->columns)) {
                foreach ($row->columns as $name => $options) {
                    $dataTypes[$row->name][$name] = $options->type;
                }
            }
            return array_keys((array)$row->columns);
        });
        $fields = &$structure['fields'];
        if (!empty($fields) && is_array($fields)) {
            $subForms = [];
            // add all fields
            foreach ($fields as $index => &$field) {
                if (array_key_exists('name', $field) && $field['name'] && $field['type'] != "subform") {
                    $columnName = $this->createSlug(strtolower($field['name']));
                    $oldColumnName = $this->createSlug(strtolower($field['oldName']));
                    $field['name'] = $columnName;
                    if ($columnName && !in_array($columnName, $columns[$tableName]) && !in_array($oldColumnName, $columns[$tableName])) {
                        $bi->createCommand()->addColumn($tableName, $columnName, $field['dataType'])->execute();
                        $structure['fields'][$index]['oldName'] = $field['name'];
                    } else if ($columnName && $columnName != $oldColumnName) {
                        // rename the column name
                        $bi->createCommand()->renameColumn($tableName, $oldColumnName, $columnName)->execute();
                        $structure['fields'][$index]['oldName'] = $field['name'];
                    } else if (isset($dataTypes[$tableName][$columnName]) && $field['dataType'] != $dataTypes[$tableName][$columnName]) {
                        // change column type
                        $bi->createCommand()->alterColumn($tableName, $columnName, $field['dataType'])->execute();
                    }
                } else if ($field['type'] == "subform") {
                    $subForms[] = &$field;
                }
            }
            // apply all sub forms in this node
            if (!empty($subForms) && is_array($subForms)) {
                foreach ($subForms as &$field) {
                    $this->manageTable($field, $tableName);
                }
            }
        }
    }

    protected function createSlug($str, $delimiter = '_')
    {

        $slug = strtolower(trim(preg_replace('/[\s-]+/', $delimiter, preg_replace('/[^A-Za-z0-9-]+/', $delimiter, preg_replace('/[&]/', 'and', preg_replace('/[\']/', '', iconv('UTF-8', 'ASCII//TRANSLIT', $str))))), $delimiter));
        return $slug;

    }

    public function tablesFields($structure = null)
    {
        if (!$structure) {
            $structure = $this->structure;
        }
        $list = [];
        $list[$structure['name']] = [];
        if (isset($structure['fields']) && !empty($structure['fields']) && is_array($structure['fields'])) {
            foreach ($structure['fields'] as $field) {
                if (isset($field['type']) && !in_array($field['type'], ['separator', 'title'])) {
                    if ($field['type'] == 'subform') {
                        $list = array_merge($list, $this->tablesFields($field));
                    } else {
                        $list[$structure['name']][$field['name']] = [
                            'required' => filter_var($field['required'], FILTER_VALIDATE_BOOLEAN),
                            'validation' => $field['validation'],
                        ];
                    }
                }
            }
        }
        return $list;
    }

    public function sortFormData($data, $relations)
    {
        $sorter = new StringSort();
        if (!empty($relations) && is_array($relations)) {
            foreach ($relations as $tableName => $deps) {
                $sorter->add($tableName, array_keys($deps));
            }
        }
        $result = $sorter->sort();
        $list = [];

        if (!empty($result) && is_array($result)) {
            foreach ($result as $tableName) {
                if (isset($data[$tableName])) {
                    $list[$tableName] = $data[$tableName];
                }
            }
        }
        return $list;
    }

    public function toArray(array $fields = [], array $expand = [], $recursive = true)
    {
        $list = parent::toArray($fields, $expand, $recursive);
        $structure = $list['structure'];
        $this->fixStructureNames($structure);
        $list['structure'] = $structure;
        return $list;
    }

    public function fixStructureNames(&$structure, $parentName = null)
    {
        if (isset($structure['name'])) {
            $structure['name'] = $this->createSlug(strtolower(($parentName && is_string($parentName) ? $parentName . "_" : "") . $structure['name']));
            $structure['oldName'] = $structure['name'];
            if (isset($structure['fields'])) {
                $fields = $structure['fields'];
                if (!empty($fields) && is_array($fields)) {
                    foreach ($fields as $index => $field) {
                        if (in_array($field['type'], ['separator', 'title'])) {
                            continue;
                        } else if ($field['type'] == 'subform') {
                            $this->fixStructureNames($structure['fields'][$index], $structure['name']);
                        } else {
                            $structure['fields'][$index]['name'] = $this->createSlug(strtolower($field['name']));
                            $structure['fields'][$index]['oldName'] = $structure['fields'][$index]['name'];
                        }
                    }
                }
            }
        }
    }

    public function crudData($tableName, $page = 1, $pageSize = 25, $parentId = null, $search = null, $order = null)
    {
        $crudModel = DynamicForm::generateModel($tableName);
        $dataLocator = DataLocator::create($crudModel::className(), [
            'orderBy' => $order ? $order : 'updated_at DESC, created_at DESC, id DESC',
            'page' => $page,
            'pageSize' => $pageSize
        ], function ($dl, $query) use ($parentId, $search, $tableName) {
            /**
             * @var $dl DataLocator
             * @var $query ActiveQuery
             * @var $m ActiveRecord
             */
            if ($parentId > 0) {
                $m = new $dl->query->modelClass();
                if ($m && $m->hasProperty('parent_relation_id')) {
                    $query->andWhere(['parent_relation_id' => $parentId]);
                }
            }
            if ($search) {
                $bi = Yii::$app->bi;
                $attrs = array_filter(arrayHelper::map($bi->schema->getTableSchema($tableName)->columns, function ($row) {
                    return $row->name;
                }, function ($row) {
                    if (in_array($row->name, ['parent_relation_id', 'created_at', 'updated_at'])) {
                        return null;
                    }
                    return $row->type;
                }));
                if (!empty($attrs) && is_array($attrs)) {
                    $q = [];
                    foreach ($attrs as $name => $type) {
                        if (in_array($type, ["string", "text"])) {
                            $q[] = '`' . $name . '` like "%' . $search . '%"';
                        } else if (in_array($type, ["smallint", "integer", "bigint", "float", "decimal", "money"])) {
                            $q[] = '`' . $name . '` in (' . $search . ')';
                        } else if (in_array($type, ["datetime", "date", "time"])) {
                            $q[] = '`' . $name . '` = "' . $search . '"';
                        }
                    }
                    if (count($q) > 0) {
                        $query->andWhere(implode(' OR ', $q));
                    }
                }
            }
        });
        $response = [
            'data' => $dataLocator->getData(),
            'count' => count($dataLocator->getData()),
            'totalCount' => intval($dataLocator->getDataCount()),
            'currentPage' => intval($dataLocator->getPage()),
        ];
        return $response;
    }
}
