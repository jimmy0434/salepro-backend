<?php

namespace common\models;

use Yii;
use yii\helpers\ArrayHelper;
use yii\helpers\Json;

/**
 * This is the model class for table "{{%certification}}".
 *
 * @property int $id
 * @property string $title
 * @property string $image
 * @property string $source
 * @property string $date
 *

 */
class News extends \common\components\ActiveRecord
{

    public $imageFactory;

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return '{{%news}}';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return array_merge(parent::rules(), [
            [['title'], 'required'],
            [['title', 'source', 'url','details'], 'string'],
           
        ]);
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'title' => 'Title',
            'image' => 'Image',
            'source' => 'Name',
            'url' => 'Url',
            'details'=>'Details',
        ];
    }

 



    /**
     * {@inheritdoc}
     * @return NewsQuery the active query used by this AR class.
     */
    public static function find()
    {
        return new NewsQuery(get_called_class());
    }


    public function toArray(array $fields = [], array $expand = [], $recursive = true)
    {
        $formatter = \Yii::$app->formatter;
        $list = parent::toArray($fields, $expand, $recursive);
       
        $list['image'] = $this->imageFactory->url;
       
    
       
        $list['date'] = Yii::$app->formatter->asDate($this->created_at, 'php:Y-m-d');

    
        return $list;

        
        
    }

    public function beforeSave($insert)
    {
        if (is_array($this->image)) {
            $this->image = Json::encode($this->image);
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function afterFind()
    {
        parent::afterFind();
        if (is_string($this->image) && Yii::$app->helper->isJson($this->image)) {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => $this->image,
            ]);
        } else {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => Yii::$app->image->defaultUser,
            ]);
        }
    }

   

  public function sendNotification()
    {
        $users = array_values(ArrayHelper::map(User::find()->where(['status' => User::STATUS_ACTIVE, 'type' => User::TYPE_SALESMAN])->all(), 'id', 'id'));
        Yii::$app->notification->send('news-update', [
            'message' => 'News Update',
            'id' => $this->id,
        ], $users);
    }
}
