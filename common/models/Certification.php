<?php

namespace common\models;

use cnd\core\components\ActiveRecord;
use Yii;
use yii\helpers\Json;

/**
 * This is the model class for table "{{%certification}}".
 *
 * @property int $id
 * @property string $name
 * @property string $image
 * @property int $file_id
 * @property int $created_at
 * @property int $updated_at
 *
 * @property BusinessUnitCertification[] $businessUnitCertifications
 * @property File $file
 * @property ProductCertification[] $productCertifications
 */
class Certification extends ActiveRecord
{

    public $imageFactory;

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return '{{%certification}}';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return array_merge(parent::rules(), [
            [['name'], 'required'],
            [['file_id'], 'integer'],
            [['name'], 'string', 'max' => 255],
            [['file_id'], 'exist', 'skipOnError' => true, 'targetClass' => File::className(), 'targetAttribute' => ['file_id' => 'id']],
        ]);
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'name' => 'Name',
            'image' => 'Image',
            'file_id' => 'File ID',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    /**
     * @return \yii\db\ActiveQuery
     */
    public function getCertificationBusinessUnits()
    {
        return $this->hasMany(BusinessUnitCertification::className(), ['certification_id' => 'id']);
    }

    public function getBusinessUnits()
    {
        return $this->hasMany(BusinessUnit::className(), ['id' => 'business_unit_id'])->via('certificationBusinessUnits');
    }

    /**
     * @return \yii\db\ActiveQuery
     */
    public function getFile()
    {
        return $this->hasOne(File::className(), ['id' => 'file_id']);
    }

    /**
     * @return \yii\db\ActiveQuery
     */
    public function getCertificationProducts()
    {
        return $this->hasMany(ProductCertification::className(), ['certification_id' => 'id']);
    }

    public function getProducts()
    {
        return $this->hasMany(Product::className(), ['id' => 'product_id'])->via('certificationProducts');
    }

    /**
     * {@inheritdoc}
     * @return CertificationQuery the active query used by this AR class.
     */
    public static function find()
    {
        return new CertificationQuery(get_called_class());
    }

    public function beforeSave($insert)
    {
        if (is_array($this->image)) {
            $this->image = Json::encode($this->image);
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function afterFind()
    {
        parent::afterFind();
        if (is_string($this->image) && Yii::$app->helper->isJson($this->image)) {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => $this->image,
            ]);
        } else {
            $this->imageFactory = \Yii::createObject([
                'class' => 'cnd\filemanager\components\FileOutput',
                'data' => Yii::$app->image->defaultUser,
            ]);
        }
    }

    public function toArray(array $fields = [], array $expand = [], $recursive = true)
    {
        $list = parent::toArray($fields, $expand, $recursive);
        unset($list['file_id']);
        $list['file'] = $this->file;
        $list['image'] = $this->imageFactory->url;
        return $list;
    }
}
